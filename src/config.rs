/// 集成模式 modprobe 配置：黑名单 + install 拦截所有 NVIDIA 和 nouveau
///
/// 同时使用 `blacklist` 和 `install … /bin/false` 实现双重保险：
/// - blacklist 阻止 modprobe 按名称加载模块
/// - install 拦截任何尝试加载模块的操作（包括依赖加载）
pub const MODPROBE_INTEGRATED: &str = r#"# Automatically generated by gswitch
blacklist nouveau
blacklist nvidia
blacklist nvidia-drm
blacklist nvidia-modeset
blacklist nvidia-uvm
install nouveau /bin/false
install nvidia /bin/false
install nvidia-drm /bin/false
install nvidia-modeset /bin/false
install nvidia-uvm /bin/false
"#;

