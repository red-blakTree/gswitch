//! gswitch 配置常量

use std::cell::RefCell;

// ====== 路径注入 (便于测试) ======

thread_local! {
    static CUSTOM_ROOT: RefCell<Option<String>> = const { RefCell::new(None) };
}

/// 仅供测试：将实际根文件系统替换为临时目录
/// 使用 thread-local 存储，支持并行测试
#[doc(hidden)]
pub fn set_root_for_test(root: &str) {
    CUSTOM_ROOT.with(|r| *r.borrow_mut() = Some(root.to_string()));
}

/// 仅供测试：清除测试根目录
#[doc(hidden)]
pub fn clear_root_for_test() {
    CUSTOM_ROOT.with(|r| *r.borrow_mut() = None);
}

/// 解析路径：如果设置了测试根，则拼接前缀；否则原样返回
pub(crate) fn resolve_path(path: &str) -> String {
    CUSTOM_ROOT.with(|r| {
        if let Some(root) = r.borrow().as_ref() {
            format!("{}{}", root.trim_end_matches('/'), path)
        } else {
            path.to_string()
        }
    })
}

/// 是否处于测试模式（路径注入已设置）
pub(crate) fn is_test_mode() -> bool {
    CUSTOM_ROOT.with(|r| r.borrow().is_some())
}

// ====== 全局 dry-run 标志 ======

thread_local! {
    static DRY_RUN: RefCell<Option<bool>> = const { RefCell::new(None) };
}

/// 设置 dry-run 模式（所有写入操作仅打日志，不实际执行）
#[doc(hidden)]
pub fn set_dry_run(enabled: bool) {
    DRY_RUN.with(|r| *r.borrow_mut() = Some(enabled));
}

pub(crate) fn is_dry_run() -> bool {
    DRY_RUN.with(|r| r.borrow().unwrap_or(false))
}

